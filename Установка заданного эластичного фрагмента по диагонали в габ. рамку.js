let file = 'D:\\YandexDisk\\Модерн\\Фрагменты\\Построение\\Фурнитура\\Крепеж\\Двойная_стяжка_гор.fr3d';
let frag = OpenFurniture(file);
if (frag) {
    let obj = frag.Make();
    obj.Owner = Model.Temp;

    // Получение двух точек: начало координат и правый верхний ближний угол
    let p1 = GetPoint("Укажите начало координат (левый нижний дальний угол)");
    let p2 = GetPoint("Укажите правый верхний ближний угол");

    // Преобразуем точки в векторы
    p1 = new Vector(p1.x, p1.y, p1.z);  // Левый нижний дальний угол
    p2 = new Vector(p2.x, p2.y, p2.z);  // Правый верхний ближний угол

    // Определяем позицию фрагмента по первой точке
    obj.Position = p1; // Устанавливаем позицию фрагмента в начало координат

    // Вычисляем размеры для ElasticResize
    let width = Math.abs(p2.x - p1.x); // Ширина между двумя точками
    let height = 16; // фиксированная высота
    let depth = Math.abs(p2.z - p1.z); // Глубина между двумя точками

    // Устанавливаем размеры фрагмента
    obj.ElasticResize({ x: width, y: height, z: depth });

    // Обновление фрагмента
    obj.Build();
}
